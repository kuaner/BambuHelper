#!/usr/bin/env python3
"""Embed the unchanged, licensed Studio PNGs for the P4-only dashboard."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "include/p4_printer_artwork.h"
lines = ["// Generated by scripts/generate_p4_artwork.py; see assets/p4/NOTICE.md.",
         "#pragma once", "#include <stdint.h>", "#include <stddef.h>"]
for path in sorted((ROOT / "assets/p4/printers").glob("*.png")):
    data = path.read_bytes()
    lines.append(f"static const uint8_t p4_art_{path.stem}[] = {{")
    lines.extend("  " + ",".join(f"0x{b:02x}" for b in data[i:i+24]) + ","
                 for i in range(0, len(data), 24))
    lines.append("};")
OUT.write_text("\n".join(lines) + "\n")
